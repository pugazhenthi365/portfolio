/**
 * Generates supabase/seed.sql from src/content/seed.ts so the database and the
 * fallback data layer always start from identical content.
 *
 *   npm run db:seed-sql      (Node >= 22.18, uses built-in TypeScript type stripping)
 */
import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";
import { seedContent } from "../src/content/seed.ts";

type Value = string | number | boolean | null | undefined | string[];

function lit(v: Value): string {
  if (v === null || v === undefined) return "null";
  if (typeof v === "boolean") return v ? "true" : "false";
  if (typeof v === "number") return String(v);
  if (Array.isArray(v)) return v.length ? `array[${v.map(lit).join(", ")}]::text[]` : "'{}'::text[]";
  return `'${v.replace(/'/g, "''")}'`;
}

function insert(table: string, rows: Record<string, Value>[]) {
  if (!rows.length) return "";
  const cols = Object.keys(rows[0]);
  const values = rows.map((r) => `  (${cols.map((c) => lit(r[c])).join(", ")})`).join(",\n");
  return `insert into public.${table} (${cols.join(", ")}) values\n${values}\non conflict (id) do nothing;\n`;
}

const { profile, settings, experiences, projects, skillCategories, education, certifications } = seedContent;

const { updated_at: _pu, ...profileRow } = profile;
const { updated_at: _su, ...settingsRow } = settings;

const sql = [
  "-- Generated by scripts/generate-seed-sql.ts — do not edit by hand.",
  "-- Idempotent: safe to run more than once (existing rows are left untouched).",
  "begin;",
  insert("profiles", [profileRow as unknown as Record<string, Value>]),
  insert("site_settings", [settingsRow as unknown as Record<string, Value>]),
  insert("experiences", experiences as unknown as Record<string, Value>[]),
  insert(
    "projects",
    projects.map(({ images: _i, created_at: _c, updated_at: _u, ...p }) => p) as unknown as Record<string, Value>[],
  ),
  insert("skill_categories", skillCategories.map(({ skills: _s, ...c }) => c) as unknown as Record<string, Value>[]),
  insert("skills", skillCategories.flatMap((c) => c.skills) as unknown as Record<string, Value>[]),
  insert("education", education as unknown as Record<string, Value>[]),
  insert("certifications", certifications as unknown as Record<string, Value>[]),
  "commit;",
  "",
].join("\n");

const out = join(dirname(fileURLToPath(import.meta.url)), "..", "supabase", "seed.sql");
writeFileSync(out, sql);
console.log(`Wrote ${out}`);
